from sqlalchemy import (
    Column,
    Integer,
    String,
    Text,
    Date,
    DateTime,
    Numeric,
    ForeignKey,
    Enum,
    Time,
)
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func

from .database import Base


# =========================
# CATEGORIES
# =========================

class Category(Base):
    __tablename__ = "categories"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String(100), nullable=False, unique=True)
    description = Column(Text, nullable=True)
    created_at = Column(DateTime, server_default=func.current_timestamp())

    shops = relationship("Shop", back_populates="category")


# =========================
# SHOPS
# =========================

class Shop(Base):
    __tablename__ = "shops"

    id = Column(Integer, primary_key=True, index=True)
    shop_code = Column(String(20), unique=True, nullable=False)
    name = Column(String(150), nullable=False)
    category_id = Column(Integer, ForeignKey("categories.id"), nullable=False)
    floor = Column(String(30), nullable=False)
    area_sqft = Column(Numeric(10, 2), nullable=False)
    monthly_rent = Column(Numeric(12, 2), nullable=False)

    status = Column(
        Enum("OCCUPIED", "VACANT", "MAINTENANCE"),
        nullable=False,
        default="VACANT",
    )

    created_at = Column(DateTime, server_default=func.current_timestamp())

    category = relationship("Category", back_populates="shops")
    leases = relationship("Lease", back_populates="shop")

    # Retail sales generated by this shop
    sales = relationship(
        "Sale",
        back_populates="shop"
    )

    # Support / maintenance requests for this shop
    support_requests = relationship(
        "SupportRequest",
        back_populates="shop"
    )


