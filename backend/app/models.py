# =========================
# RETAIL SALES
# =========================
#
# This is DIFFERENT from the existing
# manager payment/collection system.
#
# Retail Sale:
#
# Tenant → Shop → Customer Purchase
#
# Example:
# Aarav → Zara F-101 → Customer buys Jacket
#
# =========================

class Sale(Base):
    __tablename__ = "sales"

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    sale_number = Column(
        String(30),
        unique=True,
        nullable=False,
        index=True,
    )

    # -------------------------
    # Shop
    # -------------------------

    shop_id = Column(
        Integer,
        ForeignKey("shops.id"),
        nullable=False,
    )

    # -------------------------
    # Tenant
    # -------------------------

    tenant_id = Column(
        Integer,
        ForeignKey("tenants.id"),
        nullable=False,
    )

    # -------------------------
    # Customer
    # -------------------------

    customer_name = Column(
        String(150),
        nullable=False,
    )

    customer_phone = Column(
        String(20),
        nullable=True,
    )

    # -------------------------
    # Product
    # -------------------------

    product_name = Column(
        String(200),
        nullable=False,
    )

    product_category = Column(
        String(100),
        nullable=True,
    )

    # -------------------------
    # Pricing
    # -------------------------

    quantity = Column(
        Integer,
        nullable=False,
        default=1,
    )

    unit_price = Column(
        Numeric(12, 2),
        nullable=False,
    )

    total_amount = Column(
        Numeric(12, 2),
        nullable=False,
    )

    # -------------------------
    # Payment
    # -------------------------

    payment_method = Column(
        Enum(
            "CASH",
            "CARD",
            "UPI",
            "BANK_TRANSFER",
        ),
        nullable=False,
    )

    transaction_reference = Column(
        String(100),
        nullable=True,
    )

    # -------------------------
    # Dates
    # -------------------------

    sale_date = Column(
        DateTime,
        nullable=False,
        server_default=func.current_timestamp(),
    )

    created_at = Column(
        DateTime,
        server_default=func.current_timestamp(),
    )

    # -------------------------
    # Relationships
    # -------------------------

    shop = relationship(
        "Shop",
        back_populates="sales",
    )

    tenant = relationship(
        "Tenant",
        back_populates="sales",
    )


# =========================
# SUPPORT / MAINTENANCE
# =========================
#
# Tenant creates a request
# for their leased shop.
#
# Tenant → Active Lease → Shop
#                    ↓
#             Support Request
#
# Manager can view and update
# all support requests.
#
# =========================

class SupportRequest(Base):
    __tablename__ = "support_requests"

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    request_number = Column(
        String(30),
        unique=True,
        nullable=False,
        index=True,
    )

    # -------------------------
    # Shop
    # -------------------------

    shop_id = Column(
        Integer,
        ForeignKey("shops.id"),
        nullable=False,
    )

    # -------------------------
    # Tenant
    # -------------------------

    tenant_id = Column(
        Integer,
        ForeignKey("tenants.id"),
        nullable=False,
    )

    # -------------------------
    # Request Type
    # -------------------------

    request_type = Column(
        Enum(
            "MAINTENANCE",
            "ELECTRICAL",
            "PLUMBING",
            "CLEANING",
            "SECURITY",
            "HVAC",
            "IT",
            "OTHER",
        ),
        nullable=False,
        default="MAINTENANCE",
    )

    # -------------------------
    # Request Details
    # -------------------------

    subject = Column(
        String(200),
        nullable=False,
    )

    description = Column(
        Text,
        nullable=False,
    )

    # -------------------------
    # Priority
    # -------------------------

    priority = Column(
        Enum(
            "LOW",
            "MEDIUM",
            "HIGH",
            "URGENT",
        ),
        nullable=False,
        default="MEDIUM",
    )

    # -------------------------
    # Status
    # -------------------------

    status = Column(
        Enum(
            "OPEN",
            "IN_PROGRESS",
            "RESOLVED",
            "CLOSED",
        ),
        nullable=False,
        default="OPEN",
    )

    # -------------------------
    # Manager Response
    # -------------------------

    manager_response = Column(
        Text,
        nullable=True,
    )

    # -------------------------
    # Dates
    # -------------------------

    created_at = Column(
        DateTime,
        server_default=func.current_timestamp(),
    )

    updated_at = Column(
        DateTime,
        server_default=func.current_timestamp(),
        onupdate=func.current_timestamp(),
    )

    # -------------------------
    # Relationships
    # -------------------------

    shop = relationship(
        "Shop",
        back_populates="support_requests",
    )

    tenant = relationship(
        "Tenant",
        back_populates="support_requests",
    )